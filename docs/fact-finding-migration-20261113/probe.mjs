import {pathToFileURL} from 'node:url';
const root=process.argv[2];
const {Store}=await import(pathToFileURL(root+'/packages/redtrace-engine/src/store.ts'));
const {graphTools}=await import(pathToFileURL(root+'/packages/redtrace-engine/src/runner.ts'));
const store=new Store(':memory:');
const {project}=store.createProject({title:'fixture',origin:'authorized fixture',goal:'verify fixture',bootstrap:false});
const fact=store.addFact(project.id,'Verified fixture summary',{title:'Fixture title',evidence:[{description:'Fixture evidence'}]});
const finding=store.addFinding(project.id,{title:'Fixture finding',description:'Finding summary',factIds:[fact.id]});
const step=store.addStep(project.id,{description:'read fixture',sourceIds:['origin']});
const run=store.claim(project.id,'execute',{name:'fixture',backend:'mock'},step.id);
const config={workspaceRoot:'/tmp',maxSteps:null};
const tools=graphTools({store,run,worker:{name:'fixture'},config,signal:new AbortController().signal},()=>{});
const read=async args=>(await tools.find(t=>t.name==='read_graph').execute('fixture',args)).details;
const graph=await read({}),summary=await read({id:fact.id});
console.log(JSON.stringify({title:fact.title??null,defaultContainsDescription:JSON.stringify(graph).includes('Verified fixture summary'),supportingFactFolded:!graph.facts.some(f=>f.id===fact.id),summary:summary.description,rawFactRetained:store.node(project.id,fact.id).description,findingFacts:store.node(project.id,finding.id).factIds.length}));
store.close();
